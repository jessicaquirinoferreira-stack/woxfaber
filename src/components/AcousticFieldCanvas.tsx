import React, { useEffect, useRef } from 'react';

interface WavePulse {
  x: number;
  y: number;
  radius: number;
  maxRadius: number;
  alpha: number;
  speed: number;
}

export const AcousticFieldCanvas: React.FC<{ className?: string }> = ({ className = '' }) => {
  const canvasRef = useRef<HTMLCanvasElement>(null);

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext('2d', { alpha: true });
    if (!ctx) return;

    let animationFrameId: number;
    let width = (canvas.width = canvas.parentElement?.clientWidth || window.innerWidth);
    let height = (canvas.height = canvas.parentElement?.clientHeight || window.innerHeight);

    let mouseX = width * 0.5;
    let mouseY = height * 0.45;
    let targetMouseX = mouseX;
    let targetMouseY = mouseY;
    let isHovering = false;

    const pulses: WavePulse[] = [];

    // Periodic natural sub-bass pulse (45Hz feeling ~ 1.2s cycles)
    let lastAutoPulse = 0;

    const handleResize = () => {
      if (!canvas.parentElement) return;
      width = canvas.width = canvas.parentElement.clientWidth;
      height = canvas.height = canvas.parentElement.clientHeight;
    };

    const handleMouseMove = (e: MouseEvent) => {
      const rect = canvas.getBoundingClientRect();
      targetMouseX = e.clientX - rect.left;
      targetMouseY = e.clientY - rect.top;
      isHovering = true;
    };

    const handleMouseLeave = () => {
      isHovering = false;
      targetMouseX = width * 0.5;
      targetMouseY = height * 0.45;
    };

    const handleClick = (e: MouseEvent) => {
      const rect = canvas.getBoundingClientRect();
      const x = e.clientX - rect.left;
      const y = e.clientY - rect.top;
      pulses.push({
        x,
        y,
        radius: 5,
        maxRadius: Math.max(width, height) * 0.75,
        alpha: 0.85,
        speed: 4.5,
      });
    };

    window.addEventListener('resize', handleResize);
    canvas.addEventListener('mousemove', handleMouseMove);
    canvas.addEventListener('mouseleave', handleMouseLeave);
    canvas.addEventListener('click', handleClick);

    let time = 0;

    const render = () => {
      time += 0.02;

      // Smooth mouse interpolation
      mouseX += (targetMouseX - mouseX) * 0.08;
      mouseY += (targetMouseY - mouseY) * 0.08;

      ctx.clearRect(0, 0, width, height);

      // 1. Ambient Acoustic Horizon / Isobar Grid
      const rows = 18;
      const cols = 28;
      const stepX = width / cols;
      const stepY = height / rows;

      ctx.lineWidth = 1;

      for (let r = 0; r <= rows; r++) {
        const yBase = r * stepY;
        ctx.beginPath();
        for (let c = 0; c <= cols; c++) {
          const x = c * stepX;
          // Calculate distance from acoustic focal point
          const dx = x - mouseX;
          const dy = yBase - mouseY;
          const dist = Math.sqrt(dx * dx + dy * dy);

          // Physical wave propagation: sin(k*r - w*t) / sqrt(r)
          const wavelength = 65;
          const phase = dist / wavelength - time * 2.5;
          const amplitude = Math.sin(phase) * Math.max(0, 18 - dist * 0.015);

          const y = yBase + amplitude;

          if (c === 0) {
            ctx.moveTo(x, y);
          } else {
            ctx.lineTo(x, y);
          }
        }
        const alpha = Math.max(0.02, 0.15 - (r / rows) * 0.08);
        ctx.strokeStyle = `rgba(59, 130, 246, ${alpha})`;
        ctx.stroke();
      }

      // 2. High-SPL Pressure concentric rings from acoustic source
      const numRings = 6;
      const baseSpeed = 1.5;
      for (let i = 0; i < numRings; i++) {
        const radius = ((time * 30 * baseSpeed + (i * 90)) % (width * 0.65));
        const ringAlpha = Math.max(0, (1 - radius / (width * 0.65)) * 0.22);

        ctx.beginPath();
        ctx.arc(mouseX, mouseY, radius, 0, Math.PI * 2);
        ctx.strokeStyle = i % 2 === 0 ? `rgba(96, 165, 250, ${ringAlpha})` : `rgba(37, 99, 235, ${ringAlpha * 0.8})`;
        ctx.lineWidth = i % 2 === 0 ? 1.4 : 0.8;
        ctx.stroke();
      }

      // 3. Shockwave Pulses generated by clicks or bass hits
      const now = Date.now();
      if (now - lastAutoPulse > 2800) {
        lastAutoPulse = now;
        pulses.push({
          x: mouseX,
          y: mouseY,
          radius: 8,
          maxRadius: Math.max(width, height) * 0.55,
          alpha: 0.45,
          speed: 2.8,
        });
      }

      for (let i = pulses.length - 1; i >= 0; i--) {
        const p = pulses[i];
        p.radius += p.speed;
        p.alpha *= 0.985;

        if (p.alpha <= 0.01 || p.radius >= p.maxRadius) {
          pulses.splice(i, 1);
          continue;
        }

        const gradient = ctx.createRadialGradient(p.x, p.y, p.radius * 0.85, p.x, p.y, p.radius);
        gradient.addColorStop(0, 'rgba(37, 99, 235, 0)');
        gradient.addColorStop(0.5, `rgba(96, 165, 250, ${p.alpha * 0.45})`);
        gradient.addColorStop(1, 'rgba(126, 194, 251, 0)');

        ctx.beginPath();
        ctx.arc(p.x, p.y, p.radius, 0, Math.PI * 2);
        ctx.strokeStyle = `rgba(126, 194, 251, ${p.alpha})`;
        ctx.lineWidth = 1.6;
        ctx.stroke();
      }

      // 4. Acoustic Transducer Focal Indicator
      const glowGrad = ctx.createRadialGradient(mouseX, mouseY, 0, mouseX, mouseY, 150);
      glowGrad.addColorStop(0, 'rgba(59, 130, 246, 0.22)');
      glowGrad.addColorStop(0.5, 'rgba(37, 99, 235, 0.05)');
      glowGrad.addColorStop(1, 'rgba(0, 0, 0, 0)');

      ctx.fillStyle = glowGrad;
      ctx.beginPath();
      ctx.arc(mouseX, mouseY, 150, 0, Math.PI * 2);
      ctx.fill();

      // Precision crosshair / acoustic phase center
      ctx.strokeStyle = 'rgba(96, 165, 250, 0.55)';
      ctx.lineWidth = 1;
      const chSize = 10;

      ctx.beginPath();
      ctx.moveTo(mouseX - chSize, mouseY);
      ctx.lineTo(mouseX + chSize, mouseY);
      ctx.moveTo(mouseX, mouseY - chSize);
      ctx.lineTo(mouseX, mouseY + chSize);
      ctx.stroke();

      ctx.beginPath();
      ctx.arc(mouseX, mouseY, 3.5, 0, Math.PI * 2);
      ctx.fillStyle = '#60A5FA';
      ctx.fill();

      animationFrameId = requestAnimationFrame(render);
    };

    render();

    return () => {
      cancelAnimationFrame(animationFrameId);
      window.removeEventListener('resize', handleResize);
      canvas.removeEventListener('mousemove', handleMouseMove);
      canvas.removeEventListener('mouseleave', handleMouseLeave);
      canvas.removeEventListener('click', handleClick);
    };
  }, []);

  return (
    <canvas
      ref={canvasRef}
      className={`absolute inset-0 pointer-events-auto cursor-crosshair ${className}`}
      aria-label="Simulador interativo de campo acústico e pressão sonora"
    />
  );
};
